
#Write program with parameter using return value

#Addition :
def add(a,b):
    return a+b

result_add = add(10,20)
print(f"Addition of two number: {result_add}")

#Substraction
def sub(x,y):
    return x-y
result_sub = sub(30,25)
print(f"Substraction of two numbers: {result_sub}")

#Multiplication
def mul(q,r):
    return q*r
result_mul = mul(5,3)
print(f"Multiplication of two numbers: {result_mul}")

#Division
def div(s,t):
    return s/t
result_div = div(2,10)
print(f"Division of two numbers: {result_div}")