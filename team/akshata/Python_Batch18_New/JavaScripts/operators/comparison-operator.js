

// 2.Comparison Operators

// Always return TRUE or FALSE (boolean)
let q =10;
let r = 20;
let s = "10";

// equal to ==
console.log(`q==r : ${q==r}`); // false
console.log(`q==s : ${q==s}`);  //true
console.log(`q===s : ${q===s}`); // equal to and equal type

// not equal to !=
console.log(`q!=r : ${q!=r}`); //true
console.log(`q!=r : ${q!=s}`); // false
console.log(`q!==r : ${q!==s}`); //not equal to or not equsl to type

// > Greater than
console.log(`r > q  :  ${r > q}`); //true
console.log(`q > r  : ${q > r}`);  //false

// > less than
console.log(`r < q  :  ${r < q}`); //false
console.log(`q < r  :  ${q < r}`);  //true

// > Greater than equal to
console.log(`r >= q  :  ${r >= q}`); //true
console.log(`q >= r  :  ${q >= r}`);  //false

// > lessr than equal to
console.log(`r <= q  :  ${r <= q}`); //false
console.log(`q <= r  :   ${q <= r}`);  //true
