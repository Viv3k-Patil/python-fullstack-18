
// Assignment operator
let t = 15;
console.log(`Initial value of t : ${t}`); // 15

// += (Addition Assignment)
t += 15;  // t = t + 15
console.log(`After t += 15     : ${t}`);  // 30

// -= (Subtraction Assignment)
t -= 15;  // t = t -15
console.log(`After t -= 15     : ${t}`);  // 15

// *= (Multiplication Assignment)
t *= 15;  // t = t * 15
console.log(`After t *= 15     : ${t}`);  // 225

// /= (Division Assignment)
t /= 15;  // t = t / 15
console.log(`After t /= 15     : ${t}`);  // 15

// %= (Modulus Assignment)
t %= 4;  // t = t % 4
console.log(`After t %= 4      : ${t}`);  // 3

// **= (Exponentiation Assignment)
t **= 3;    // t = t ** 3
console.log(`After t **= 3     : ${t}`);  // 27
