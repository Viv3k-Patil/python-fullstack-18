# Loops / iterations in python!!
# For loops are used to repeat code multiple times

# Example 1:
#  Loop through a list of names

list_name = ['onkar','om','jay','shree']

for name in list_name:
    print("Hello", name)


# Example 2: Loop through numbers using range()

for number in range(6,0,-2):  # range(1, 6) gives us 1, 2, 3, 4, 5
    print("Number:", number)

